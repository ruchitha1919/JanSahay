def language_label(language: str) -> str:
    return LANGUAGE_LABELS.get(language, language)


def language_from_label(label: str) -> str:
    try:
        return next(language for language, native_label in LANGUAGE_LABELS.items() if native_label == label)
    except StopIteration as error:
        raise ValueError(f"Unsupported language label: {label}") from error


def translate_text(text: str, language: str) -> str:
    translations = _TEXT.get(language)
    if not translations:
        return text

    translated = text
    for source, target in sorted(translations.items(), key=lambda item: len(item[0]), reverse=True):
        translated = re.sub(
            rf"(?<!\w){re.escape(source)}(?!\w)",
            lambda _match, replacement=target: replacement,
            translated,
            flags=re.IGNORECASE,
        )
    return translated


def translate_options(options, language: str) -> tuple[str, ...]:
    return tuple(translate_text(str(option), language) for option in options)


def original_option(label: str, options, language: str) -> str:
    for option in options:
        original = str(option)
        if translate_text(original, language) == label:
            return original
    raise ValueError(f"Unknown translated option: {label}")


class LocalizedStreamlit:
    """Translate visible Streamlit text while preserving widget values."""

    _CONTENT_METHODS = {
        "caption", "error", "exception", "header", "info", "markdown", "success",
        "subheader", "text", "title", "warning", "write",
    }
    _LABEL_METHODS = {
        "button", "checkbox", "date_input", "file_uploader", "form_submit_button",
        "link_button", "number_input", "radio", "segmented_control", "selectbox",
        "text_area", "text_input", "chat_input",
    }
    _CHOICE_METHODS = {"radio", "segmented_control", "selectbox"}
    _CONTAINER_METHODS = {
        "chat_message", "columns", "container", "empty", "expander", "form",
        "popover", "sidebar", "tabs",
    }

    def __init__(self, target: object, get_language: Callable[[], str]):
        object.__setattr__(self, "_target", target)
        object.__setattr__(self, "_get_language", get_language)

    def __getattr__(self, name: str):
        target = object.__getattribute__(self, "_target")
        value = getattr(target, name)
        if name in self._CONTAINER_METHODS:
            if name == "sidebar":
                return LocalizedStreamlit(value, self._get_language)

            def container_method(*args, **kwargs):
                if name == "tabs" and args:
                    args = (self._translate_value(args[0]), *args[1:])
                result = value(*args, **kwargs)
                return self._wrap_result(result)

            return container_method
        if name in self._CONTENT_METHODS:
            def content_method(*args, **kwargs):
                args = tuple(self._translate_value(item) for item in args)
                kwargs = {key: self._translate_value(item) for key, item in kwargs.items()}
                return value(*args, **kwargs)

            return content_method
        if name in self._LABEL_METHODS:
            def label_method(*args, **kwargs):
                args = list(args)
                if args:
                    args[0] = self._translate_value(args[0])
                for key in ("label", "placeholder", "help"):
                    if key in kwargs:
                        kwargs[key] = self._translate_value(kwargs[key])
                return value(*args, **kwargs)

            return label_method
        return value

    def __enter__(self):
        entered = self._target.__enter__()
        return self._wrap_result(entered)

    def __exit__(self, exc_type, exc_value, traceback):
        return self._target.__exit__(exc_type, exc_value, traceback)

    def _translate_value(self, value: object):
        language = self._get_language()
        if isinstance(value, str):
            return translate_text(value, language)
        if isinstance(value, tuple):
            return tuple(self._translate_value(item) for item in value)
        if isinstance(value, list):
            return [self._translate_value(item) for item in value]
        return value

    def _wrap_result(self, value: object):
        if isinstance(value, list):
            return [self._wrap_result(item) for item in value]
        if isinstance(value, tuple):
            return tuple(self._wrap_result(item) for item in value)
        return LocalizedStreamlit(value, self._get_language)
